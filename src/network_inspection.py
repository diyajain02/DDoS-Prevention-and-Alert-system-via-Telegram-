    def _get_flow_key(self, src_ip: str, dst_ip: str, src_port: int, dst_port: int, protocol: Protocol) -> str:
        """Generate a unique flow key."""
        # Normalize direction for flow tracking
        if src_ip < dst_ip or (src_ip == dst_ip and src_port < dst_port):
            return f"{src_ip}:{src_port}-{dst_ip}:{dst_port}-{protocol.value}"
        else:
            return f"{dst_ip}:{dst_port}-{src_ip}:{src_port}-{protocol.value}"

    def _match_rule(self, rule: IPSRule, flow: NetworkFlow, payload: bytes = b'') -> Optional[str]:
        """Check if a flow matches an IPS rule."""
        if not rule.enabled:
            return None

        # Protocol match
        if rule.protocol != Protocol.UNKNOWN and rule.protocol != flow.protocol:
            return None

        # Direction match
        if rule.direction != Direction.BOTH and rule.direction != flow.direction:
            return None

        # IP matches
        if rule.src_ips and not self._ip_in_list(flow.src_ip, rule.src_ips):
            return None
        if rule.dst_ips and not self._ip_in_list(flow.dst_ip, rule.dst_ips):
            return None

        # Port matches
        if rule.src_ports and flow.src_port not in rule.src_ports:
            return None
        if rule.dst_ports and flow.dst_port not in rule.dst_ports:
            return None

        # Payload patterns
        if rule.payload_patterns and payload:
            payload_str = payload.decode('utf-8', errors='ignore')
            for pattern in rule.payload_patterns:
                if re.search(pattern, payload_str, re.IGNORECASE):
                    return f"payload_pattern: {pattern}"

        # Payload contains
        if rule.payload_contains and payload:
            payload_str = payload.decode('utf-8', errors='ignore')
            for substr in rule.payload_contains:
                if substr.lower() in payload_str.lower():
                    return f"payload_contains: {substr}"

        # HTTP-specific
        if flow.protocol == Protocol.HTTP and flow.http_info:
            if rule.http_methods and flow.http_info.get('method') not in rule.http_methods:
                return None
            if rule.http_paths:
                path = flow.http_info.get('path', '')
                matched = False
                for path_pattern in rule.http_paths:
                    if re.search(path_pattern, path):
                        matched = True
                        return f"http_path: {path_pattern}"
                if not matched:
                    return None
            if rule.http_headers:
                headers = flow.http_info.get('headers', {})
                for hdr, pattern in rule.http_headers.items():
                    if hdr.lower() not in [h.lower() for h in headers]:
                        return None
                    if not re.search(pattern, headers.get(hdr, ''), re.IGNORECASE):
                        return None

        # TLS SNI
        if flow.protocol == Protocol.TLS and flow.tls_info:
            sni = flow.tls_info.get('sni', '')
            for pattern in rule.tls_sni_patterns:
                if re.search(pattern, sni, re.IGNORECASE):
                    return f"tls_sni: {pattern}"

        # DNS queries
        if flow.protocol == Protocol.DNS and flow.dns_queries:
            for query in flow.dns_queries:
                for pattern in rule.dns_query_patterns:
                    if re.search(pattern, query, re.IGNORECASE):
                        return f"dns_query: {pattern}"

        # Behavioral thresholds
        if rule.threshold_count > 0 and rule.threshold_window > 0:
            # This would need flow aggregation - simplified for now
            if flow.bytes_sent + flow.bytes_received >= rule.threshold_count:
                return f"threshold_exceeded: {rule.threshold_count} bytes in {rule.threshold_window}s"

        return None

    def _ip_in_list(self, ip: str, ip_list: List[str]) -> bool:
        """Check if IP matches any in list (supports CIDR)."""
        import ipaddress
        try:
            ip_obj = ipaddress.ip_address(ip)
            for cidr in ip_list:
                if ip_obj in ipaddress.ip_network(cidr):
                    return True
        except ValueError:
            pass
        return False

    def process_packet(self, src_ip: str, dst_ip: str, src_port: int, dst_port: int, 
                       protocol: Protocol, direction: Direction, payload: bytes = b'',
                       length: int = 0, flags: Set[str] = None):
        """Process a network packet."""
        if not self.enabled:
            return

        flow_key = self._get_flow_key(src_ip, dst_ip, src_port, dst_port, protocol)
        
        with self.flow_lock:
            if flow_key not in self.flows:
                self.flows[flow_key] = NetworkFlow(
                    flow_id=flow_key,
                    src_ip=src_ip,
                    dst_ip=dst_ip,
                    src_port=src_port,
                    dst_port=dst_port,
                    protocol=protocol,
                    direction=direction,
                    start_time=datetime.now(),
                    last_seen=datetime.now(),
                )
                self.stats['flows_tracked'] += 1
            
            flow = self.flows[flow_key]
            flow.last_seen = datetime.now()
            
            if direction == Direction.OUTBOUND or (direction == Direction.BOTH and src_ip == flow.src_ip):
                flow.bytes_sent += length
                flow.packets_sent += 1
            else:
                flow.bytes_received += length
                flow.packets_received += 1
            
            if flags:
                flow.flags.update(flags)

            # Detect application protocol if not yet identified
            if not flow.application and payload:
                detected = ApplicationDetector.detect_from_payload(payload, dst_port, src_port)
                if detected:
                    flow.application = detected.value
                    
                    # Application-specific parsing
                    if detected == Protocol.TLS:
                        tls_info = TLSInspector.parse_client_hello(payload)
                        if tls_info:
                            flow.tls_info = tls_info
                    elif detected == Protocol.HTTP:
                        # Parse HTTP (simplified)
                        http_info = self._parse_http(payload)
                        if http_info:
                            flow.http_info = http_info
                    elif detected == Protocol.DNS:
                        # Parse DNS (simplified)
                        dns_queries = self._parse_dns(payload)
                        if dns_queries:
                            flow.dns_queries = dns_queries

        # Check against rules
        self._check_rules(flow, payload)

        self.stats['packets_processed'] += 1
        self.stats['bytes_processed'] += length

    def _parse_http(self, payload: bytes) -> Optional[Dict]:
        """Parse HTTP request/response."""
        try:
            payload_str = payload.decode('utf-8', errors='ignore')
            lines = payload_str.split('\r\n')
            if not lines:
                return None
            
            # Request line
            request_line = lines[0]
            parts = request_line.split(' ', 2)
            if len(parts) < 3:
                return None
            
            method, path, version = parts
            headers = {}
            for line in lines[1:]:
                if not line:
                    break
                if ':' in line:
                    key, value = line.split(':', 1)
                    headers[key.strip()] = value.strip()
            
            body = '\r\n'.join(lines[lines.index('')+1:]) if '' in lines else ''
            
            # Run HTTP inspector
            alerts = HTTPInspector.inspect_request(method, path, headers, body)
            
            return {
                'method': method,
                'path': path,
                'version': version,
                'headers': headers,
                'body': body[:1000],  # Limit body size
                'alerts': alerts,
            }
        except Exception:
            return None

    def _parse_dns(self, payload: bytes) -> List[str]:
        """Parse DNS queries from payload."""
        queries = []
        try:
            if len(payload) < 12:
                return queries
            
            # Skip header (12 bytes)
            offset = 12
            qdcount = struct.unpack('!H', payload[4:6])[0]
            
            for _ in range(qdcount):
                if offset >= len(payload):
                    break
                
                # Parse domain name (simplified - no compression handling)
                labels = []
                while offset < len(payload):
                    length = payload[offset]
                    if length == 0:
                        offset += 1
                        break
                    if length & 0xC0:  # Compression pointer
                        break
                    offset += 1
                    if offset + length > len(payload):
                        break
                    labels.append(payload[offset:offset+length].decode('utf-8', errors='ignore'))
                    offset += length
                
                if labels:
                    queries.append('.'.join(labels))
                
                offset += 4  # Skip qtype and qclass
            
        except Exception:
            pass
        
        return queries

    def _check_rules(self, flow: NetworkFlow, payload: bytes):
        """Check flow against all IPS rules."""
        for rule in self.rules:
            match_info = self._match_rule(rule, flow, payload)
            if match_info:
                alert = IPSAlert(
                    rule=rule,
                    flow=flow,
                    matched_data=match_info,
                    action_taken=rule.action,
                )
                
                with self.alert_lock:
                    self.alerts.append(alert)
                    self.stats['alerts_generated'] += 1
                
                flow.alerts.append(f"{rule.id}: {match_info}")
                
                # Take action
                if rule.action == Action.BLOCK:
                    self._block_flow(flow)
                elif rule.action == Action.DROP:
                    # Would drop packet in real implementation
                    pass
                
                logger.warning(f"IPS Alert: {rule.name} ({rule.id}) - {match_info}")

    def _block_flow(self, flow: NetworkFlow):
        """Block the flow by blocking the attacker IP."""
        # Determine which IP to block based on direction
        if flow.direction == Direction.INBOUND:
            block_ip = flow.src_ip
        else:
            block_ip = flow.dst_ip
        
        try:
            from src.blocker import get_blocker
            blocker = get_blocker()
            blocker.block_ip(block_ip, f"IPS: {flow.alerts[-1] if flow.alerts else 'Rule match'}", 3600)
        except Exception as e:
            logger.error(f"Failed to block IP {block_ip}: {e}")

    def get_alerts(self) -> List[IPSAlert]:
        """Get recent alerts."""
        with self.alert_lock:
            return list(self.alerts[-100:])  # Last 100 alerts

    def get_alerts_as_log_entries(self) -> List[LogEntry]:
        """Get alerts as LogEntry for detection engine."""
        with self.alert_lock:
            return [alert.to_log_entry() for alert in self.alerts[-100:]]

    def get_stats(self) -> Dict:
        """Get monitoring statistics."""
        with self.flow_lock:
            active_flows = len(self.flows)
        return {
            **self.stats,
            'active_flows': active_flows,
            'rules_loaded': len(self.rules),
        }

    def start(self):
        """Start network monitoring (requires root/raw socket)."""
        if self.running:
            return
        
        # Note: Real implementation would use raw sockets, AF_PACKET, or libpcap
        # For now, this is a framework that can be extended
        logger.warning("NetworkMonitor.start() - Real packet capture requires root privileges and raw socket implementation")
        self.running = True
        
        # Start cleanup thread
        self.cleanup_thread = threading.Thread(target=self._cleanup_loop, daemon=True)
        self.cleanup_thread.start()

    def stop(self):
        """Stop network monitoring."""
        self.running = False
        if self.cleanup_thread:
            self.cleanup_thread.join(timeout=5)
        logger.info("Network Monitor stopped")

    def _cleanup_loop(self):
        """Clean up old flows."""
        while self.running:
            time.sleep(60)  # Cleanup every minute
            if not self.running:
                break
            
            cutoff = datetime.now().timestamp() - 300  # 5 minutes
            with self.flow_lock:
                expired = [
                    key for key, flow in self.flows.items()
                    if flow.last_seen.timestamp() < cutoff
                ]
                for key in expired:
                    del self.flows[key]

