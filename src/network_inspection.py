@dataclass
class IPSRule:
    """Intrusion Prevention System rule."""
    id: str
    name: str
    description: str
    severity: str  # CRITICAL, HIGH, MEDIUM, LOW, INFO
    category: str  # exploit, malware, c2, scan, policy, etc.
    protocol: Protocol
    direction: Direction = Direction.INBOUND
    
    # Matching criteria
    src_ips: List[str] = field(default_factory=list)  # CIDR or IP
    dst_ips: List[str] = field(default_factory=list)
    src_ports: List[int] = field(default_factory=list)
    dst_ports: List[int] = field(default_factory=list)
    
    # Payload patterns
    payload_patterns: List[str] = field(default_factory=list)  # regex patterns
    payload_contains: List[str] = field(default_factory=list)  # simple string contains
    
    # Application layer
    http_methods: List[str] = field(default_factory=list)
    http_paths: List[str] = field(default_factory=list)
    http_headers: Dict[str, str] = field(default_factory=dict)
    tls_sni_patterns: List[str] = field(default_factory=list)
    dns_query_patterns: List[str] = field(default_factory=list)
    
    # Behavioral
    threshold_count: int = 0
    threshold_window: int = 0  # seconds
    
    action: Action = Action.ALERT
    enabled: bool = True
    tags: List[str] = field(default_factory=list)
    references: List[str] = field(default_factory=list)


@dataclass
class IPSAlert:
    """Alert generated by IPS rule match."""
    rule: IPSRule
    flow: NetworkFlow
    matched_data: str
    timestamp: datetime = field(default_factory=datetime.now)
    action_taken: Action = Action.ALERT

    def to_log_entry(self) -> LogEntry:
        """Convert to LogEntry for detection engine."""
        details = {
            'rule_id': self.rule.id,
            'rule_name': self.rule.name,
            'severity': self.rule.severity,
            'category': self.rule.category,
            'src_ip': self.flow.src_ip,
            'dst_ip': self.flow.dst_ip,
            'src_port': self.flow.src_port,
            'dst_port': self.flow.dst_port,
            'protocol': self.flow.protocol.value,
            'direction': self.flow.direction.value,
            'action_taken': self.action_taken.value,
            'matched_data': self.matched_data[:500],  # Truncate
            'application': self.flow.application,
        }
        return LogEntry(
            timestamp=self.timestamp,
            raw_line=f"IPS Alert: {self.rule.name} ({self.rule.id}) - {self.flow.src_ip}:{self.flow.src_port} -> {self.flow.dst_ip}:{self.flow.dst_port}",
            source_ip=self.flow.src_ip if self.flow.direction == Direction.INBOUND else self.flow.dst_ip,
            username="system",
            event_type="ips_alert",
            details=details,
        )


class ApplicationDetector:
    """Detects application protocols from network traffic."""

    # Port-based hints (not definitive)
    COMMON_PORTS = {
        20: Protocol.FTP, 21: Protocol.FTP,
        22: Protocol.SSH,
        23: Protocol.TELNET,
        25: Protocol.SMTP, 465: Protocol.SMTP, 587: Protocol.SMTP,
        53: Protocol.DNS,
        80: Protocol.HTTP, 8080: Protocol.HTTP, 8000: Protocol.HTTP, 8888: Protocol.HTTP,
        443: Protocol.HTTPS, 8443: Protocol.HTTPS,
        110: Protocol.POP3, 995: Protocol.POP3,
        143: Protocol.IMAP, 993: Protocol.IMAP,
        389: Protocol.LDAP, 636: Protocol.LDAP,
        445: Protocol.SMB,
        3389: Protocol.RDP,
        5432: Protocol.POSTGRES,
        3306: Protocol.MYSQL,
        1433: Protocol.MSSQL,
        6379: Protocol.REDIS,
        27017: Protocol.MONGODB,
    }

    # Protocol signatures (first bytes of payload)
    SIGNATURES = {
        Protocol.SSH: [b'SSH-'],
        Protocol.TLS: [b'\x16\x03\x01', b'\x16\x03\x02', b'\x16\x03\x03', b'\x16\x03\x04'],  # TLS 1.0-1.3
        Protocol.HTTP: [b'GET ', b'POST ', b'PUT ', b'DELETE ', b'HEAD ', b'OPTIONS ', b'PATCH ', b'CONNECT ', b'TRACE '],
        Protocol.DNS: [],  # DNS has no fixed signature, uses port 53
    }

    @classmethod
    def detect_from_port(cls, port: int) -> Optional[Protocol]:
        """Guess protocol from port number."""
        return cls.COMMON_PORTS.get(port)

    @classmethod
    def detect_from_payload(cls, payload: bytes, dport: int = 0, sport: int = 0) -> Optional[Protocol]:
        """Detect protocol from payload content."""
        if not payload:
            return None

        # Check TLS/SSL first (common on many ports)
        if payload.startswith(b'\x16\x03'):
            return Protocol.TLS

        # Check SSH
        if payload.startswith(b'SSH-'):
            return Protocol.SSH

        # Check HTTP methods
        http_methods = [b'GET ', b'POST ', b'PUT ', b'DELETE ', b'HEAD ', b'OPTIONS ', b'PATCH ', b'CONNECT ', b'TRACE ']
        for method in http_methods:
            if payload.startswith(method):
                return Protocol.HTTP

        # Check DNS (port 53 with valid DNS header)
        if (dport == 53 or sport == 53) and len(payload) >= 12:
            # Basic DNS header check: QR=0 (query), standard query
            flags = struct.unpack('!H', payload[2:4])[0]
            if (flags & 0x8000) == 0:  # QR bit = 0 (query)
                return Protocol.DNS

        # Port-based fallback
        return cls.detect_from_port(dport) or cls.detect_from_port(sport)


class TLSInspector:
    """Inspects TLS handshakes for SNI, certificates, etc."""

    @staticmethod
    def parse_client_hello(payload: bytes) -> Optional[Dict]:
        """Parse TLS Client Hello to extract SNI."""
        if len(payload) < 5 or not payload.startswith(b'\x16\x03'):
            return None

        try:
            # Skip record header (5 bytes)
            offset = 5
            if offset >= len(payload):
                return None

            # Handshake header: type (1) + length (3)
            if offset + 4 > len(payload):
                return None
            
            handshake_type = payload[offset]
            if handshake_type != 0x01:  # Client Hello
                return None
            
            offset += 4  # Skip handshake header
            
            # Client Hello structure:
            # protocol_version (2) + random (32) + session_id_len (1) + session_id + cipher_suites_len (2) + cipher_suites + compression_methods_len (1) + compression_methods + extensions_len (2) + extensions
            
            if offset + 34 > len(payload):  # version + random
                return None
            offset += 34
            
            # Session ID
            if offset >= len(payload):
                return None
            session_id_len = payload[offset]
            offset += 1 + session_id_len
            
            if offset >= len(payload):
                return None
            
            # Cipher suites
            cipher_suites_len = struct.unpack('!H', payload[offset:offset+2])[0]
            offset += 2 + cipher_suites_len
            
            if offset >= len(payload):
                return None
            
            # Compression methods
            comp_methods_len = payload[offset]
            offset += 1 + comp_methods_len
            
            if offset >= len(payload):
                return None
            
            # Extensions
            if offset + 2 > len(payload):
                return None
            extensions_len = struct.unpack('!H', payload[offset:offset+2])[0]
            offset += 2
            
            end_offset = offset + extensions_len
            while offset + 4 <= end_offset and offset < len(payload):
                ext_type = struct.unpack('!H', payload[offset:offset+2])[0]
                ext_len = struct.unpack('!H', payload[offset+2:offset+4])[0]
                offset += 4
                
                if ext_type == 0x0000:  # SNI (Server Name Indication)
                    if offset + 2 > len(payload):
                        break
                    sni_list_len = struct.unpack('!H', payload[offset:offset+2])[0]
                    offset += 2
                    
                    # SNI list: each entry has type (1) + len (2) + name
                    while offset < len(payload) and offset < end_offset:
                        if offset >= len(payload):
                            break
                        name_type = payload[offset]
                        offset += 1
                        if offset + 2 > len(payload):
                            break
                        name_len = struct.unpack('!H', payload[offset:offset+2])[0]
                        offset += 2
                        if offset + name_len > len(payload):
                            break
                        sni = payload[offset:offset+name_len].decode('utf-8', errors='ignore')
                        offset += name_len
                        return {'sni': sni}
                
                offset += ext_len
            
        except Exception as e:
            logger.debug(f"TLS parse error: {e}")
        
        return None


class HTTPInspector:
    """Inspects HTTP traffic for suspicious patterns."""

    # Common attack patterns
    SQL_INJECTION_PATTERNS = [
        r"(\bunion\b.*\bselect\b)",
        r"(\bor\b\s+['\"]?1['\"]?\s*=\s*['\"]?1)",
        r"(';|--|\bor\b\s+\d+=\d+)",
        r"(\bdrop\b\s+\btable\b)",
        r"(\binsert\b\s+\binto\b)",
        r"(\bselect\b.*\bfrom\b)",
        r"(\bexec\b\s*\()",
    ]

    XSS_PATTERNS = [
        r"<script[^>]*>",
        r"javascript:",
        r"on\w+\s*=",
        r"<iframe[^>]*>",
        r"alert\s*\(",
        r"eval\s*\(",
        r"document\.cookie",
    ]

    PATH_TRAVERSAL_PATTERNS = [
        r"\.\./",
        r"\.\.\\",
        r"%2e%2e%2f",
        r"%2e%2e/",
    ]

    COMMAND_INJECTION_PATTERNS = [
        r"[;&|`$]\s*(cat|ls|id|whoami|wget|curl|nc|bash|sh)\b",
        r"\$\(",
        r"`.*`",
    ]

    @classmethod
    def inspect_request(cls, method: str, path: str, headers: Dict, body: str) -> List[str]:
        """Inspect HTTP request for attack patterns."""
        alerts = []
        combined = f"{method} {path} {headers} {body}".lower()

        for pattern in cls.SQL_INJECTION_PATTERNS:
            if re.search(pattern, combined, re.IGNORECASE):
                alerts.append(f"SQL Injection attempt: {pattern}")
                break

        for pattern in cls.XSS_PATTERNS:
            if re.search(pattern, combined, re.IGNORECASE):
                alerts.append(f"XSS attempt: {pattern}")
                break

        for pattern in cls.PATH_TRAVERSAL_PATTERNS:
            if re.search(pattern, combined, re.IGNORECASE):
                alerts.append(f"Path traversal attempt: {pattern}")
                break

        for pattern in cls.COMMAND_INJECTION_PATTERNS:
            if re.search(pattern, combined, re.IGNORECASE):
                alerts.append(f"Command injection attempt: {pattern}")
                break

        return alerts


class DNSInspector:
    """Inspects DNS traffic for suspicious queries."""

    # Suspicious TLDs and patterns
    SUSPICIOUS_TLDS = {'.tk', '.ml', '.ga', '.cf', '.gq', '.xyz', '.top', '.club', '.work', '.date'}
    DGA_PATTERNS = [
        r'^[a-z]{20,}\.(com|net|org)$',  # Long random subdomains
        r'^[0-9a-f]{32,}\.(com|net|org)$',  # Hash-like subdomains
    ]

    @classmethod
    def inspect_query(cls, query: str) -> List[str]:
        """Inspect DNS query for suspicious patterns."""
        alerts = []
        query_lower = query.lower()

        # Check suspicious TLDs
        for tld in cls.SUSPICIOUS_TLDS:
            if query_lower.endswith(tld):
                alerts.append(f"Suspicious TLD: {tld}")
                break

        # Check DGA patterns
        for pattern in cls.DGA_PATTERNS:
            if re.search(pattern, query_lower):
                alerts.append(f"Possible DGA domain: {query}")
                break

        # Check for excessive subdomains (fast flux)
        if query.count('.') > 5:
            alerts.append(f"Excessive subdomains: {query}")

        # Check for known C2 patterns
        c2_patterns = ['dyndns', 'no-ip', 'duckdns', 'freedynamicdns']
        for pattern in c2_patterns:
            if pattern in query_lower:
                alerts.append(f"Dynamic DNS (possible C2): {query}")
                break

        return alerts


